import os, asyncio, subprocess, time, json, urllib.parse
from playwright.async_api import async_playwright
SS=os.environ.get('KASIR_TES_DATA','tests/data/')
srv=subprocess.Popen(['python3','-m','http.server','8832','-d','dist'],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL);time.sleep(1)
BK=json.load(open(SS+'bk/backup.json'))
fails=[]
def cek(ok,msg):
    print(('OK   ' if ok else 'GAGAL ')+msg,flush=True)
    if not ok: fails.append(msg)
async def main():
  async with async_playwright() as p:
    b=await p.chromium.launch()
    pg=await b.new_page(viewport={'width':1333,'height':750});errs=[];pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.set_default_timeout(10000)
    await pg.goto('http://localhost:8832/index.html');await pg.wait_for_timeout(700)
    async with pg.expect_navigation():
        await pg.evaluate("o=>restore(o)",BK)
    await pg.wait_for_timeout(1800)
    notes=await pg.evaluate("[...document.querySelectorAll('.modal .notes li')].map(l=>l.innerText)")
    cek(any('Supplier' in n for n in notes) and any('Tagih utang' in n for n in notes),'pemberitahuan versi baru (supplier, tagih utang)')
    await pg.evaluate("document.querySelectorAll('.modal').forEach(m=>m.remove())")
    await pg.evaluate("()=>{window._wo=[];window.open=u=>{window._wo.push(u);return {}}}")
    # ---------- menu atas muat ----------
    nav=await pg.evaluate("(()=>{const n=document.querySelector('#nav');return [n.scrollWidth,n.clientWidth,!!n.querySelector('[data-v=supplier]')]})()")
    cek(nav[2] and nav[0]<=nav[1]+1,'menu Supplier ada dan menu atas tidak perlu digeser (%s)'%nav[:2])
    # ---------- tombol samping kasir ----------
    await pg.click('nav button[data-v=kasir]');await pg.wait_for_timeout(300)
    await pg.evaluate("document.querySelectorAll('.modal').forEach(m=>m.remove());S.meta.tundaBuka=dkey(Date.now());render()");await pg.wait_for_timeout(200)
    w=await pg.evaluate("(()=>{const g=document.querySelector('.aksi2');const bs=[...g.children].map(x=>Math.round(x.getBoundingClientRect().width));return {n:bs.length,bs,g:Math.round(g.getBoundingClientRect().width),h:Math.round(document.querySelector('#histBtn').getBoundingClientRect().width),o:Math.round(document.querySelector('#ordBtn').getBoundingClientRect().width)}})()")
    cek(w['n']==6 and max(w['bs'])-min(w['bs'])<=2,'6 tombol samping sama lebar %s'%w['bs'])
    cek(abs(w['h']-w['g'])<=2 and abs(w['o']-w['g'])<=2,'Riwayat & Pesanan pelanggan selebar kolom (%s/%s/%s)'%(w['h'],w['o'],w['g']))
    ids=await pg.evaluate("[...document.querySelector('.aksi2').children].map(x=>x.id)")
    cek('lastBtn' in ids and 'clearBtn' in ids,'Struk terakhir & Kosongkan sejajar di grid')
    # ---------- form produk ----------
    await pg.click('nav button[data-v=produk]');await pg.wait_for_timeout(300)
    await pg.click('#addP');await pg.wait_for_timeout(300)
    f=await pg.evaluate("(()=>{const b=document.querySelector('.modal .box').getBoundingClientRect(),a=document.querySelector('.modal .actbar').getBoundingClientRect(),k=document.querySelector('#fkd').getBoundingClientRect(),s=document.querySelector('#fsk').getBoundingClientRect();return {bb:b.bottom,vh:innerHeight,ab:a.bottom,kt:k.top,st:s.top,kh:k.height,sh:s.height}})()")
    cek(f['bb']<=f['vh'] and abs(f['ab']-f['bb'])<=2,'jendela tidak melebihi layar, tombol Simpan menempel di bawah (%s)'%f)
    cek(abs(f['kt']-f['st'])<=1 and abs(f['kh']-f['sh'])<=2,'kotak Kode singkat sejajar dengan Singkatan otomatis')
    await pg.evaluate("document.querySelectorAll('.modal').forEach(m=>m.remove())")

    # ---------- tagih utang lewat WA ----------
    await pg.evaluate("""(async()=>{const c={id:'cTG',nama:'BU ENTIN',tier:'umum',telp:'',alamat:'',aktif:true};await save('customers',c);
      const d=n=>Date.now()-n*864e5;
      await save('payments',{id:'u1',jenis:'utang',customerId:'cTG',waktu:d(20),jumlah:50000,kas:'warung',catatan:'dari buku'});
      await save('payments',{id:'u2',jenis:'utang',customerId:'cTG',waktu:d(2),jumlah:30000,kas:'warung',catatan:''});
      await save('payments',{id:'u3',customerId:'cTG',waktu:d(1),jumlah:20000,kas:'warung'});})()""")
    r=await pg.evaluate("rincianUtang('cTG').map(x=>[x.sisa,x.sebagian])")
    cek(r==[[30000,True],[30000,False]],'rincian utang: cicilan menutup utang paling lama dulu %s'%r)
    await pg.click('nav button[data-v=beranda]');await pg.wait_for_timeout(300)
    att=await pg.evaluate("[...document.querySelectorAll('.att')].map(a=>a.innerText)")
    cek(any('utang lebih dari 2 minggu' in a for a in att),'Beranda: pengingat utang pelanggan lebih dari 2 minggu')
    await pg.click('nav button[data-v=pelanggan]');await pg.wait_for_timeout(300)
    await pg.click('[data-tg=cTG]');await pg.wait_for_timeout(200)
    t=await pg.input_value('#tgT')
    cek('Total sisa utang: Rp 60.000' in t and 'Bu Entin' in t and '0813-2168-5590' in t and '(sisa, sudah dicicil)' in t,'isi pesan tagihan lengkap (rincian, total, WA toko)')
    cek('—' not in t and ';' not in t,'pesan tagihan tanpa em dash / titik koma')
    await pg.click('#tgGo');await pg.wait_for_timeout(200)
    cek('No. WhatsApp' in await pg.inner_text('#toast') and not await pg.evaluate("window._wo.length"),'No. WA kosong: diminta isi dulu')
    await pg.fill('#tgHp','0812-3456-7890');await pg.click('#tgGo');await pg.wait_for_timeout(300)
    u=await pg.evaluate("window._wo.at(-1)||''")
    cek(u.startswith('https://wa.me/6281234567890?text=') and 'Rp%2060.000' in u,'WhatsApp dibuka ke nomor pelanggan dengan pesan tagihan')
    c=await pg.evaluate("(()=>{const c=S.customers.find(x=>x.id==='cTG');return [c.telp,!!c.ditagih]})()")
    cek(c==['0812-3456-7890',True],'No. HP tersimpan ke data pelanggan, tanggal ditagih dicatat')
    cek('ditagih' in await pg.inner_text('#main'),'daftar pelanggan menampilkan "ditagih <tanggal>"')

    # ---------- supplier ----------
    await pg.click('nav button[data-v=supplier]');await pg.wait_for_timeout(300)
    cek('Belum ada supplier' in await pg.inner_text('#main'),'halaman Supplier terbuka')
    await pg.click('#spAdd');await pg.wait_for_timeout(200)
    await pg.fill('#spN','Agen Indofood');await pg.fill('#spS','Pak Dedi');await pg.fill('#spH','0812-1111-2222');await pg.fill('#spT','14')
    await pg.fill('#spB','Indomie, Sarimi')
    await pg.click('[data-pola=mingguan]')
    hari=await pg.evaluate("new Date().getDay()")
    await pg.click(f'[data-hari="{hari}"]')
    nx=await pg.inner_text('#spNext')
    cek('hari ini' in nx,'jadwal tiap minggu hari ini: "kunjungan berikutnya hari ini" (%s)'%nx)
    await pg.click('#spOk');await pg.wait_for_timeout(300)
    sid=await pg.evaluate("daftarSup()[0].id")
    main=await pg.inner_text('#main')
    cek('Pak Dedi' in main and 'Setiap' in main,'supplier tampil dengan jadwalnya')
    cek(await pg.locator('table.agenda tr.hariini').count()>=1,'agenda: sales datang hari ini')
    # 2 minggu sekali
    k2=await pg.evaluate("(()=>{const t=dkey(Date.now());const s={jadwal:{pola:'2minggu',hari:[new Date().getDay()],mulai:t}};return [kunjunganDalam(s,0,15).length,kunjunganDalam(s,0,15).map(hariDari)]})()")
    cek(k2==[2,[0,14]],'jadwal 2 minggu sekali: hari ini dan 14 hari lagi %s'%k2)
    kb=await pg.evaluate("kunjunganDalam({jadwal:{pola:'bulanan',tanggal:31}},0,62).map(k=>k.slice(8))")
    cek(all(x in ('30','31') for x in kb) and len(kb)>=2,'jadwal bulanan tanggal 31: bulan pendek pakai tanggal terakhir %s'%kb)
    # utang ke supplier + bayar dari laci
    await pg.click('#spNota');await pg.wait_for_timeout(200)
    await pg.select_option('#nsS',sid);await pg.wait_for_timeout(100)
    jt=await pg.input_value('#nsJ')
    cek(jt==await pg.evaluate("tambahHari(dkey(Date.now()),14)"),'jatuh tempo otomatis dari tempo 14 hari (%s)'%jt)
    await pg.fill('#nsNo','F-0012');await pg.fill('#nsT','500000');await pg.click('#nsOk');await pg.wait_for_timeout(300)
    cek(await pg.evaluate("utangKeSupplier()")==500000,'utang toko ke supplier Rp 500.000 tercatat')
    sebelum=await pg.evaluate("[posisiUang('warung').saldo,rekapUang(dayStart(0),dayStart(1)).semua.laba]")
    await pg.click('[data-bayar] >> nth=0');await pg.wait_for_timeout(200)
    await pg.fill('#bnJ','200000');await pg.click('[data-bn=warung]');await pg.click('#bnOk');await pg.wait_for_timeout(300)
    sesudah=await pg.evaluate("[posisiUang('warung').saldo,rekapUang(dayStart(0),dayStart(1)).semua.laba]")
    cek(round(sebelum[0]-sesudah[0])==200000,'bayar dari laci Warung: uang laci berkurang Rp 200.000')
    cek(sebelum[1]==sesudah[1],'bayar utang supplier tidak mengurangi laba')
    cek(await pg.evaluate("utangKeSupplier()")==300000,'sisa utang Rp 300.000')
    ke=await pg.evaluate("S.kas.filter(e=>e.notaId).map(e=>[e.kategori,e.stok,e.jumlah])")
    cek(ke==[['kulakan',True,200000]],'pembayaran dicatat sebagai belanja barang dagangan %s'%ke)
    # jatuh tempo lewat -> Beranda
    await pg.evaluate("(async()=>{daftarNota()[0].jatuhTempo=tambahHari(dkey(Date.now()),-1);await saveMeta('notaSupplier')})()")
    await pg.click('nav button[data-v=beranda]');await pg.wait_for_timeout(300)
    att=await pg.evaluate("[...document.querySelectorAll('.att')].map(a=>a.innerText)")
    cek(any('jatuh tempo' in a and 'lewat' in a for a in att),'Beranda: utang supplier jatuh tempo (sudah lewat)')
    cek(any('jadwal sales datang' in a and 'Pak Dedi' in a for a in att),'Beranda: hari ini jadwal sales datang')
    # barang masuk -> utang ke supplier
    gula=await pg.evaluate("(()=>{const p=S.products.find(p=>p.nama==='GULA PUTIH CURAH 1 KG');return [p.id,p.stok,p.hargaBeli]})()")
    await pg.evaluate(f"stockDialog('masuk',[S.products.find(p=>p.id==='{gula[0]}')],null,{{}})");await pg.wait_for_timeout(200)
    await pg.fill('[data-q="0"]','10');await pg.click('[data-bk=utang]');await pg.wait_for_timeout(100)
    cek(await pg.inner_text('#sdjL')=='Jumlah utang (Rp)','pilihan Utang ke supplier di Barang masuk')
    await pg.click('#sdok');await pg.wait_for_timeout(200)
    cek('Pilih supplier' in await pg.inner_text('#toast') and await pg.evaluate(f"S.products.find(p=>p.id==='{gula[0]}').stok")==gula[1],'tanpa supplier: ditolak, stok belum berubah')
    await pg.select_option('#sdSup',sid);await pg.fill('#sdNo','F-0013');await pg.click('#sdok');await pg.wait_for_timeout(300)
    n=await pg.evaluate("daftarNota().at(-1)")
    cek(n['total']==10*gula[2] and n['noNota']=='F-0013' and n['supplierId']==sid,'nota utang dari barang masuk: total = jumlah x harga beli (%s)'%n['total'])
    cek(await pg.evaluate(f"S.products.find(p=>p.id==='{gula[0]}').stok")==gula[1]+10,'stok gula bertambah 10')
    cek(await pg.evaluate("S.kas.filter(e=>e.kategori==='kulakan'&&!e.notaId).length")==0,'utang: tidak ada uang laci yang keluar')
    # pesanan ke sales -> sudah datang
    await pg.click('nav button[data-v=supplier]');await pg.wait_for_timeout(300)
    await pg.click('#spPesan');await pg.wait_for_timeout(200)
    await pg.select_option('#psS',sid);await pg.wait_for_timeout(100)
    usul=await pg.input_value('#psD')
    cek(usul==await pg.evaluate("tambahHari(dkey(Date.now()),7)"),'perkiraan datang = kunjungan sales berikutnya (%s)'%usul)
    await pg.fill('#psD',await pg.evaluate("dkey(Date.now())"));await pg.fill('#psI','Indomie goreng 2 dus');await pg.click('#psOk');await pg.wait_for_timeout(300)
    cek(await pg.locator('[data-dtg]').count()==1,'agenda: barang pesanan datang hari ini')
    await pg.click('[data-dtg]');await pg.wait_for_timeout(300)
    cek(await pg.input_value('#sdn')=='Kiriman Agen Indofood' and 'Indomie goreng 2 dus' in await pg.inner_text('.modal'),'Sudah datang: lanjut ke Barang masuk dengan catatan supplier & isi pesanan')
    cek(await pg.evaluate("document.querySelector('#sdSup').value")==sid,'supplier sudah terpilih di Barang masuk')
    await pg.fill('#sd','indomie goreng');await pg.wait_for_timeout(200);await pg.click('#sdl [data-a] >> nth=0')
    await pg.fill('[data-q="0"]','40');await pg.click('#sdok');await pg.wait_for_timeout(400)
    cek(await pg.evaluate("daftarPesanSup()[0].selesai===true"),'pesanan ditandai sudah datang')
    # kulakan -> kirim ke sales lewat WA -> catat pesanan
    await pg.evaluate("window._wo=[]")
    await pg.evaluate("pilihSalesDialog('1. GULA PUTIH CURAH 1 KG: 5 KG')");await pg.wait_for_timeout(200)
    await pg.click('[data-ps]');await pg.wait_for_timeout(300)
    u=urllib.parse.unquote(await pg.evaluate("window._wo.at(-1)||''"))
    cek(u.startswith('https://wa.me/6281211112222?text=') and 'Pak Dedi' in u and 'Mau pesan barang' in u,'kirim daftar belanja ke WA sales')
    cek('GULA PUTIH' in await pg.input_value('#psI'),'lalu langsung bisa dicatat sebagai pesanan')
    await pg.evaluate("document.querySelectorAll('.modal').forEach(m=>m.remove())")
    # hapus nota yang sudah dibayar sebagian -> catatan uang ikut hilang
    await pg.evaluate("rincianNotaDialog(daftarNota()[0])");await pg.wait_for_timeout(200)
    await pg.click('#rnDel');await pg.wait_for_timeout(200);await pg.click('.modal [data-yes]');await pg.wait_for_timeout(300)
    cek(await pg.evaluate("S.kas.filter(e=>e.notaId).length")==0 and await pg.evaluate("daftarNota().length")==1,'hapus nota: pembayaran dari laci ikut terhapus')
    # backup
    mk=await pg.evaluate("snapshot().meta.map(x=>x.id)")
    cek(all(k in mk for k in ['suppliers','notaSupplier','pesananSupplier']),'data supplier ikut file backup')
    await pg.screenshot(path=SS+'ui/t31_supplier.png',full_page=False)
    cek(errs==[],'tanpa error JS %s'%errs)
    await b.close()
asyncio.run(main());srv.terminate()
print('GAGAL:', fails or 'tidak ada')
